#include "../../c/calypsi/aes-private.h"
static UWORD timer_vectors(void)
{
    static const struct {
        ULONG high, low, rate, ms, outHigh, outLow;
        UWORD success;
    } cases[] = {
        {0x0UL, 0x0UL, 0x32UL, 0x0UL, 0x0UL, 0x1UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0x1UL, 0x0UL, 0x2UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0x10UL, 0x0UL, 0x2UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0x11UL, 0x0UL, 0x2UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0x13UL, 0x0UL, 0x2UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0x14UL, 0x0UL, 0x2UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0x3e7UL, 0x0UL, 0x33UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0x3e8UL, 0x0UL, 0x33UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0xffffUL, 0x0UL, 0xcceUL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0x80000000UL, 0x0UL, 0x6666668UL, 1},
        {0x0UL, 0x0UL, 0x32UL, 0xffffffffUL, 0x0UL, 0xcccccceUL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x0UL, 0x0UL, 0x1UL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x1UL, 0x0UL, 0x2UL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x10UL, 0x0UL, 0x2UL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x11UL, 0x0UL, 0x3UL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x13UL, 0x0UL, 0x3UL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x14UL, 0x0UL, 0x3UL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x3e7UL, 0x0UL, 0x3dUL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x3e8UL, 0x0UL, 0x3dUL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0xffffUL, 0x0UL, 0xf5eUL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0x80000000UL, 0x0UL, 0x7ae147cUL, 1},
        {0x0UL, 0x0UL, 0x3cUL, 0xffffffffUL, 0x0UL, 0xf5c28f7UL, 1},
        {0x7UL, 0xfffffff0UL, 0x32UL, 0xffffffffUL, 0x8UL, 0xcccccbeUL, 1},
        {0x7UL, 0xfffffff0UL, 0x3cUL, 0xffffffffUL, 0x8UL, 0xf5c28e7UL, 1},
        {0xffffffffUL, 0xfffffff0UL, 0x32UL, 0xffffffffUL, 0xffffffffUL, 0xfffffff0UL, 0},
        {0xffffffffUL, 0xfffffff0UL, 0x3cUL, 0xffffffffUL, 0xffffffffUL, 0xfffffff0UL, 0},
        {0x4UL, 0x5UL, 0x0UL, 0x1UL, 0x4UL, 0x5UL, 0},
    };
    struct TimerClockRequest clock;
    UWORD i;
    for (i = 0; i < sizeof(cases)/sizeof(cases[0]); ++i) {
        clock.ticks_hi = cases[i].high;
        clock.ticks_lo = cases[i].low;
        clock.ticks_per_second = cases[i].rate;
        if (ExecAESTimerDeadline(&clock, cases[i].ms) != cases[i].success ||
            clock.ticks_hi != cases[i].outHigh || clock.ticks_lo != cases[i].outLow)
            return i+1;
    }
    return 0;
}
