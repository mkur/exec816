"""Generate filesystem transport identities; no public kernel operation."""
import json
from generate_memory import ROOT
from generate_heap import write
ABI=json.loads((ROOT/'abi/block-io.json').read_text())
def generate(check=False):
    assert ABI['abi']=='exec816.block' and ABI['revision']==1
    assert ABI['mount_bytes']==46 and ABI['backend_offset']==45
    text='; Generated by tools/generate_block_io.py; do not edit.\n'
    text+=''.join(f'PUBLIC CONST BACKEND_{k}={v}\n' for k,v in ABI['backends'].items())
    write(ROOT/'lib/io/block-backends.inc',text,check)
if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true')
    generate(p.parse_args().check)
