#!/usr/bin/env python3
"""One emitted image for exact disk/RAM statistics and bounded transport work."""
import argparse
import json
from pathlib import Path
from filesystem_audit import Audit
from generate_dos_mounts import encode
from generate_memory import PROFILE
from library_paths import read_source
from native_program import ROOT, build, compiler, require, verify_machine
from os_boundary import emulator
from test_cooperative import data
from test_dos_stack import execute, ownership
from test_sio_device import PIN


def mounts(image, fs, ide=False):
    return [dict(alias='D1', unit=2 if ide else 49, sectors=image.count,
                 sector_bytes=image.size, format=1 if fs == 'mydos' else 2,
                 profile=0 if ide else 4, access='readwrite',
                 device='ideplus.device' if ide else 'sio.device'),
            dict(alias='RAM', format=3)]


def run(output, only=None):
    output.mkdir(parents=True, exist_ok=True)
    for name in ('volume_statistics.act', 'volumetest.act'):
        (output/name).write_text(read_source(ROOT/'tests/programs'/name))
    source = read_source(ROOT/'lib/io/blockwire.act').replace(
        'USE EXEC\n', 'USE EXEC\nUSE VOLUMETEST\n', 1)
    marker = '  control=0\n'
    require(source.count(marker) == 1, 'Stale physical-transfer observer')
    source = source.replace(marker, '''  IF VOLUMETEST.armed<>0 THEN
    IF request.io_Command=EXEC.SIOCMD_TRANSACTION THEN
      BEGIN
        LET sio=EXEC.IOSIOReq POINTER(request)
        IF sio.sio_Command=$52 THEN
          VOLUMETEST.reads==+1
        ELSE
          VOLUMETEST.writes==+1
        FI
      END
    ELSEIF request.io_Command=EXEC.IDECMD_READ_SECTOR THEN
      VOLUMETEST.reads==+1
    ELSE
      VOLUMETEST.writes==+1
    FI

    IF VOLUMETEST.failure<>0 THEN
      RETURN(VOLUMETEST.failure)
    FI
  FI

'''+marker)
    # IDE command IDs are generated by the device ABI, not copied numerically.
    source = source.replace('USE VOLUMETEST\n', 'USE VOLUMETEST\nUSE IDEPLUS\n', 1)
    source = source.replace('EXEC.IDECMD_READ_SECTOR', 'IDEPLUS.READ_SECTOR')
    (output/'blockwire.act').write_text(source)
    profile = json.loads(PROFILE.read_text())
    profile['image_data_bytes'] = 4096
    memory = output/'memory.json'
    memory.write_text(json.dumps(profile, indent=2)+'\n')
    first = Audit((ROOT/'tests/fixtures/filesystem-write/mydos-128.atr').read_bytes())
    p = build(compiler(ROOT/'build/actionc', release=True), output/'volume_statistics.act',
              output, optimize=True, tasks=True, task_capacity=8,
              console_deferred=True, memory_profile=memory,
              dos_mounts=mounts(first.image, 'mydos'),
              image_data=[(0x2dffe0, bytes([0xa5])*128)])
    scenarios = [('mydos', 128), ('mydos', 256), ('sdfs', 128), ('sdfs', 256), ('sdfs', 512)]
    reports = []
    for fs, size in scenarios:
        if only is not None and only != f'{fs}-{size}':
            continue
        folder = output/f'{fs}-{size}'
        folder.mkdir(exist_ok=True)
        ide = size == 512
        if ide:
            from ideplus_media import sdfs_image, filesystem_fixture, filesystem_atr
            from test_ideplus import ide_emulator, PIN as IDE_PIN
            original = sdfs_image(ROOT/'tests/fixtures/filesystem-write/sdfs-256.atr',
                                  folder/'source.atr')
            raw, mapping = filesystem_fixture(original, readonly=False)
            media = folder/'volume.img'
            media.write_bytes(raw)
            session = ide_emulator(folder, media, writable=True)
            pin = IDE_PIN
        else:
            original = (ROOT/f'tests/fixtures/filesystem-write/{fs}-{size}.atr').read_bytes()
            media = folder/'volume.atr'
            media.write_bytes(original)
            session = emulator(ROOT/'build/altirra-sio-multi',
                               ROOT/'build/firmware/altirraos-816.rom', folder, pin=PIN)
            pin = PIN
        before = Audit(original)
        expected = getattr(before, fs)()
        with session as b:
            for key, value in pin['configuration'].items():
                b.config(key, str(value).lower() if isinstance(value, bool) else value)
            b.config('diskemu', 'generic56k')
            b.config('accuratedisk', 'false')
            machine = verify_machine(b, ROOT/'build/firmware/altirraos-816.rom', pin)
            def prepare(b):
                if not ide:
                    b.mount(0, str(media))
                b.memload(p['build']['task_storage']['BASE']+0x900,
                          encode(mounts(before.image, fs, ide)))
            try:
                runtime, _ = execute(b, p, before_run=prepare, timeout=600, frame_limit=30000)
            except Exception:
                print(fs, size, 'phase/checks', data(b, p['image'], 'VOLUMESTATISTICS_PHASE', True),
                      data(b, p['image'], 'VOLUMESTATISTICS_CHECKS', True), flush=True)
                raise
            ownership(b, p, output)
            require(data(b, p['image'], 'finished') == [1], 'Incomplete statistics fixture')
            free = int.from_bytes(bytes(data(b, p['image'], 'initialFree')), 'little')
            total = int.from_bytes(bytes(data(b, p['image'], 'initialTotal')), 'little')
            require(free == expected['free'] and total == expected['sectors'],
                    'Statistics differ from independent allocation audit')
            report = dict(status='pass', filesystem=fs, sector_bytes=size,
                          checks=data(b, p['image'], 'checks', True),
                          machine=machine, runtime=runtime, initial=expected)
        saved = filesystem_atr(media.read_bytes(), mapping, original) if ide else media.read_bytes()
        after = Audit(saved)
        require(getattr(after, fs)()['free'] == expected['free'], 'Leaked disk allocation')
        require(after.files == before.files, 'Statistics fixture changed unrelated file bytes')
        reports.append(report)
        (folder/'results.json').write_text(json.dumps(report, indent=2)+'\n')
        print('Volume statistics passed', fs, size, report['checks'], flush=True)
    (output/'results.json').write_text(json.dumps(dict(status='pass', tier='development',
        build=p['build'], scenarios=reports, bank_zero_delta=dict(fixed=0, per_task=0, idle=0)), indent=2)+'\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--only', choices=('mydos-128', 'mydos-256', 'sdfs-128', 'sdfs-256', 'sdfs-512'))
    args = parser.parse_args()
    run(args.output.resolve(), args.only)
