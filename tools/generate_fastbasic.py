#!/usr/bin/env python3
"""Generate the shared native/6502 FastBasic executable and service contract."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def products():
    abi = json.loads((ROOT/'abi/fastbasic.json').read_text())
    constants = dict(FILE_MAGIC=int.from_bytes(abi['magic'].encode(), 'little'),
                     VERSION=abi['version'], TARGET=abi['target'],
                     HEADER_BYTES=abi['header_bytes'], LOAD=abi['load'],
                     LIMIT=abi['limit'], CHANNELS=abi['channels'],
                     CHECKPOINT=abi['checkpoint'], CHECKPOINT_EVENT=abi['checkpoint_event'])
    constants.update({f'HEADER_{key.upper()}': value for key, value in abi['header'].items()})
    constants.update(abi['guest_layout'])
    constants.update({'CIO_'+key: value for key,value in abi['cio'].items()})
    constants.update(SERVICE_COUNT=len(abi['services']),SERVICE_STRIDE=abi['service_stride'])
    for index, (name, event) in enumerate(abi['services'].items()):
        constants[f'EVENT_{name}'] = event
        constants[f'SERVICE_{name}'] = abi['service_base']+index*abi['service_stride']
    action = '; SPDX-License-Identifier: MIT\n; Generated by tools/generate_fastbasic.py; do not edit.\nMODULE FBABI\n'
    assembly = '; SPDX-License-Identifier: MIT\n; Generated by tools/generate_fastbasic.py; do not edit.\n'
    for name, value in constants.items():
        action += f'PUBLIC CONST {name}='+ (f'LONGCARD(${value:x})' if value > 65535 else f'${value:x}')+'\n'
        assembly += f'FB_{name} = ${value:x}\n'
    return {ROOT/'lib/dos/fbabi.act': action+'ENDMODULE\n',
            ROOT/'ports/fastbasic/target/fastbasic.inc': assembly}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in products().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Stale generated file: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
