#!/usr/bin/env python3
"""Private menu rendering packet shared by the scene presenter and drawing adapter."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ABI = json.loads((ROOT/'abi/menu-render.json').read_text())


def layout():
    sizes = {'BYTE': (1, 1), 'CARD': (2, 2), 'INT': (2, 2), 'LONGCARD': (4, 2)}
    records = {}
    for name, fields in ABI['records'].items():
        offset, align, offsets = 0, 1, {}
        for field, kind, *counts in fields:
            size, alignment = sizes[kind]
            count = ABI['constants'].get(counts[0], counts[0]) if counts else 1
            offset = (offset+alignment-1)//alignment*alignment
            offsets[field] = offset
            offset += size*count
            align = max(align, alignment)
        size = (offset+align-1)//align*align
        sizes[name] = size, align
        records[name] = dict(size=size, alignment=align, fields=offsets)
    return records


def expected_layout():
    return [(name+' size', r['size']) for name, r in layout().items()] + [
        (name+'.'+field, offset) for name, r in layout().items()
        for field, offset in r['fields'].items()]


def files():
    act = ['; Generated by tools/generate_menu_render.py.', 'MODULE MENURENDERTYPES']
    hdr = ['/* Generated by tools/generate_menu_render.py. MIT public interface. */',
           '#ifndef EXEC_MENU_RENDER_H', '#define EXEC_MENU_RENDER_H',
           '#include <stdint.h>', '#pragma pack(push, 2)']
    ctypes = {'BYTE':'uint8_t', 'CARD':'uint16_t', 'INT':'int16_t', 'LONGCARD':'uint32_t'}
    for name, value in ABI['constants'].items():
        act.append(f'PUBLIC CONST {name}={value}')
        hdr.append(f'#define MENU_RENDER_{name} {value}')
    for name, fields in ABI['records'].items():
        act.append(f'PUBLIC TYPE {name}=[')
        hdr.append(f'struct MenuRender{name} {{')
        for field, kind, *counts in fields:
            count = counts[0] if counts else None
            act.append(f'  {kind}'+(' ARRAY' if counts else '')+f' {field}'+(f'({count})' if counts else ''))
            ctype = ctypes.get(kind, 'struct MenuRender'+kind)
            hdr.append(f'    {ctype} {field}'+(f'[MENU_RENDER_{count}]' if counts else '')+';')
        act.append(']'); hdr.append('};')
    for name, record in layout().items():
        act.append(f'PUBLIC CONST {name.upper()}_SIZE={record["size"]}')
        hdr.append(f'#define MENU_RENDER_{name.upper()}_SIZE {record["size"]}')
        act += [f'PUBLIC CONST {name.upper()}_OFFSET_{f.upper()}={o}' for f,o in record['fields'].items()]
    probe = ['/* Generated emitted-layout probe. */', '#include <stddef.h>',
             '#include "menu-render.h"', '__attribute__((section("exec_layout"))) const unsigned short __exec_layout[] = {']
    probe += [f'    sizeof(struct MenuRender{n}),' for n in layout()]
    probe += [f'    offsetof(struct MenuRender{n}, {f}),' for n,r in layout().items() for f in r['fields']]
    probe += ['};', '']
    return {ROOT/'lib/desktop/menurendertypes.act':'\n'.join(act+['ENDMODULE','']),
            ROOT/'c/include/exec816/menu-render.h':'\n'.join(hdr+['#pragma pack(pop)', '#endif','']),
            ROOT/'ports/gem4xe/aes/menu-layout.c':'\n'.join(probe).replace('"menu-render.h"','<exec816/menu-render.h>')}


if __name__ == '__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,content in files().items():
        if a.check:
            if not path.exists() or path.read_text()!=content:raise SystemExit('Stale menu rendering layout: '+str(path))
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
