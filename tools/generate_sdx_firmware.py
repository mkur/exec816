#!/usr/bin/env python3
"""Generate the ROM admission catalog; ROM bytes are never generated or shipped."""
import argparse
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT/'platform/altirraos/sdx-firmware.json'
OUTPUT = ROOT/'platform/altirraos/generated/sdx-firmware.inc'


def catalog():
    data = json.loads(CATALOG.read_text())
    assert data['visible_ranges'] == [[0xc000, 0x1000], [0xd800, 0x2800]]
    assert data['snapshot_bytes'] == 0x4000 and data['scratch_offset'] == 0x1000
    assert len({p['id'] for p in data['profiles']}) == len(data['profiles'])
    assert len({p['visible_crc32'] for p in data['profiles']}) == len(data['profiles'])
    for p in data['profiles']:
        assert p['bytes'] == 16384 and len(bytes.fromhex(p['sha256'])) == 32
        assert 0 < p['id'] <= 255
        assert all(0xc000 <= p[k] <= 0xffff for k in ('emulation_nmi', 'emulation_irq'))
    return data


def identify(raw):
    if len(raw) != 16384:
        raise ValueError('A firmware file must contain 16 KiB')
    crc = f'{zlib.crc32(raw[:0x1000]+raw[0x1800:]):08x}'
    for p in catalog()['profiles']:
        if (p['sha256'] == hashlib.sha256(raw).hexdigest() and
                p['visible_crc32'] == crc and
                all(p[k] == int.from_bytes(raw[o:o+2], 'little') for k, o in
                    (('emulation_nmi', 0x3ffa), ('emulation_irq', 0x3ffe)))):
            return p
    raise ValueError('Unrecognized firmware image')


def product():
    data = catalog()
    text = '; Generated by tools/generate_sdx_firmware.py; no ROM payload.\n'
    text += 'SDX_ROM_PROFILE = SDX_ROM_IMAGE+$1000\n'
    text += 'SDX_ROM_CRC = SDX_ROM_IMAGE+$1002\n'
    text += 'SDX_ROM_PROFILE_STRIDE = 10\n'
    text += f'SDX_ROM_PROFILE_COUNT = {len(data["profiles"])}\n'
    text += 'sdx_rom_profiles:\n'
    for p in data['profiles']:
        text += f'; {p["name"]}; file SHA-256 {p["sha256"]}\n'
        text += f'    .word {p["id"]}\n    .dword ${p["visible_crc32"]}\n'
        text += f'    .word ${p["emulation_nmi"]:04x}, ${p["emulation_irq"]:04x}\n'
    text += 'sdx_rom_crc_table:\n'
    for index in range(256):
        value = index
        for _ in range(8):
            value = (value >> 1) ^ (0xedb88320 if value & 1 else 0)
        text += f'    .dword ${value:08x}\n'
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--rom', action='append', type=Path, default=[])
    args = parser.parse_args()
    for path in args.rom:
        print(path, identify(path.read_bytes())['name'])
    text = product()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit('Stale '+str(OUTPUT.relative_to(ROOT)))
    else:
        OUTPUT.write_text(text)


if __name__ == '__main__':
    main()
