#!/usr/bin/env python3
"""Generate the ROM admission catalog; ROM bytes are never generated or shipped."""
import argparse
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT/'platform/altirraos/sdx-firmware.json'
OUTPUT = ROOT/'platform/altirraos/generated/sdx-firmware.inc'
LABELS = ROOT/'platform/altirraos/generated/sdx-firmware-labels.inc'


def catalog():
    data = json.loads(CATALOG.read_text())
    assert data['visible_ranges'] == [[0xc000, 0x1000], [0xd800, 0x2800]]
    assert data['snapshot_bytes'] == 0x4000 and data['scratch_offset'] == 0x1000
    assert len({p['id'] for p in data['profiles']}) == len(data['profiles'])
    assert len({p['visible_crc32'] for p in data['profiles']}) == len(data['profiles'])
    assert data['fallback']['id'] not in {p['id'] for p in data['profiles']}
    for p in data['profiles']:
        assert p['bytes'] == 16384 and len(bytes.fromhex(p['sha256'])) == 32
        assert 0 < p['id'] <= 255
        assert len(p['display_name'].encode('ascii')) <= 24
        assert all(0xc000 <= p[k] <= 0xffff for k in ('emulation_nmi', 'emulation_irq'))
    return data


def identify(raw):
    if len(raw) != 16384:
        raise ValueError('A firmware file must contain 16 KiB')
    crc = f'{zlib.crc32(raw[:0x1000]+raw[0x1800:]):08x}'
    digest = hashlib.sha256(raw).hexdigest()
    for p in catalog()['profiles']:
        if (p['visible_crc32'] == crc and
                all(p[k] == int.from_bytes(raw[o:o+2], 'little') for k, o in
                    (('emulation_nmi', 0x3ffa), ('emulation_irq', 0x3ffe)))):
            if p['sha256'] != digest:
                # Runtime cannot see the self-test slot. Keep its visible
                # classification and record the actual full-file identity.
                return dict(p, sha256=digest, catalog_sha256=p['sha256'],
                            file_sha256_matches=False)
            return p
    return dict(catalog()['fallback'], bytes=len(raw),
                sha256=digest, visible_crc32=crc,
                emulation_nmi=int.from_bytes(raw[0x3ffa:0x3ffc], 'little'),
                emulation_irq=int.from_bytes(raw[0x3ffe:], 'little'))


def product():
    data = catalog()
    text = '; Generated by tools/generate_sdx_firmware.py; no ROM payload.\n'
    text += 'SDX_ROM_PROFILE = SDX_ROM_IMAGE+$1000\n'
    text += 'SDX_ROM_CRC = SDX_ROM_IMAGE+$1002\n'
    text += 'SDX_ROM_PROFILE_STRIDE = 10\n'
    text += f'SDX_ROM_PROFILE_COUNT = {len(data["profiles"])}\n'
    text += f'SDX_ROM_FALLBACK_PROFILE = {data["fallback"]["id"]}\n'
    text += 'sdx_rom_profiles:\n'
    for p in data['profiles']:
        text += f'; {p["name"]}; file SHA-256 {p["sha256"]}\n'
        text += f'    .word {p["id"]}\n    .dword ${p["visible_crc32"]}\n'
        text += f'    .word ${p["emulation_nmi"]:04x}, ${p["emulation_irq"]:04x}\n'
    text += 'sdx_rom_crc_table:\n'
    for index in range(256):
        value = index
        for _ in range(8):
            value = (value >> 1) ^ (0xedb88320 if value & 1 else 0)
        text += f'    .dword ${value:08x}\n'
    return text


def labels():
    data = catalog()
    profiles = {p['id']:p['display_name'] for p in [*data['profiles'], data['fallback']]}
    names = ['UNKNOWN']+[profiles.get(i, 'UNKNOWN') for i in range(1, max(profiles)+1)]
    text = '; Generated by tools/generate_sdx_firmware.py; no ROM payload.\n'
    text += f'BOOT_ROM_PROFILE_COUNT = {len(names)}\nboot_rom_profile_offsets:\n'
    offset = 0
    for name in names:
        text += f'    .word {offset}\n'
        offset += len(name)+1
    text += 'boot_rom_profile_text:\n'
    for name in names:
        text += f'    .byte "{name}",0\n'
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--rom', action='append', type=Path, default=[])
    args = parser.parse_args()
    for path in args.rom:
        print(path, identify(path.read_bytes())['name'])
    for path, text in ((OUTPUT, product()), (LABELS, labels())):
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit('Stale '+str(path.relative_to(ROOT)))
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
