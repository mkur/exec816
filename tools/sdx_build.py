"""Memory ownership and native bindings for the opt-in SDX personality."""
import json
import re
from pathlib import Path

from generate_memory import ROOT, require, reservation_maps

ABI = json.loads((ROOT/'abi/sdx.json').read_text())


def configure(output, memory, drive_a='RAM:'):
    require(isinstance(drive_a,str) and len(drive_a)<=128
            and re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*:(?:[A-Za-z0-9_.]+/)*',drive_a),
            'SDX A: mapping must name a native volume/directory root')
    runtime = ABI['runtime']
    # Resident loader/provider strings and console state exceed the default 2 KiB.
    memory['profile']['image_data_bytes']=max(memory['profile']['image_data_bytes'],4096)
    require(runtime['resident_bank'] in memory['usable_banks'], 'SDX resident bank is unavailable')
    require(memory['task_capacity']==8, 'SDX currently requires the eight-Task profile')
    guard, count = runtime['dp_guard_bytes'], runtime['slots']
    size = count*256+guard*2
    # Allocate from the generated post-adoption map, excluding diagnostic
    # scratch. The bootstrap may occupy these bytes only before adoption.
    selected = None
    for span in memory['runtime_free_ranges']:
        page = (span['address']+guard+255)//256*256
        while page+count*256+guard <= min(span['address']+span['size'],0x8000):
            lo, hi = page-guard, page+count*256+guard
            if all(hi <= s['address'] or lo >= s['address']+s['size']
                   for s in memory['diagnostic_scratch']):
                selected=page
                break
            page+=256
        if selected is not None:
            break
    require(selected is not None, 'No aligned guest DP pool')
    region=dict(name='sdx-direct-pages',address=selected-guard,size=size)
    phases=memory['phase_reservations']
    reservation_maps(memory, list(phases['loading']),
                     list(phases['initialization'])+[dict(region)],
                     list(phases['runtime'])+[dict(region)])
    for key in ('fixed_runtime','runtime_excluding_os','runtime_including_os'):
        memory['bank_zero_budget'][key]+=size
    memory['sdx_storage']=dict(dp_base=selected,dp_reservation=region,
        fixed_bank_zero_bytes=size,per_task_bank_zero_bytes=0,
        resident_base=runtime['resident_bank']*65536,
        resident_reserved_bytes=runtime['resident_reserved_bytes'],drive_a=drive_a)
    (Path(output)/'sdxconfig.act').write_text('MODULE SDXCONFIG\n'
        f'PUBLIC CONST DP_BASE=${selected:x}\n'
        f'PUBLIC CONST RETURN_PROBE={memory.get("sdx_return_probe",0)}\n'
        '\nPUBLIC BYTE POINTER FUNC DriveA()\n\n'
        f'RETURN(BYTE POINTER(c"{drive_a}"))\n\n'
        'ENDMODULE\n')
    (Path(output)/'sdx-storage.inc').write_text(
        '; Generated by tools/sdx_build.py; post-adoption ownership.\n'
        f'SDX_DP_BASE=${selected:x}\nSDX_DP_GUARD={guard}\nSDX_DP_SLOTS={count}\n')
    (Path(output)/'sdxbind.act').write_text('''MODULE SDXBIND
USE PROGRAMIMAGE
USE SDXPROGRAM
USE SDXSERVICE

PUBLIC PROGRAMIMAGE.Image POINTER FUNC Load(BYTE POINTER bytes LONGCARD length)

RETURN(SDXPROGRAM.Load(bytes,length))

PUBLIC LONGINT FUNC Run(PROGRAMIMAGE.Image POINTER image BYTE POINTER arguments)

RETURN(SDXSERVICE.Run(image,arguments))

ENDMODULE
''')


def bindings(output, labels):
    config=Path(output)/'sdxconfig.act'
    text=config.read_text().replace('ENDMODULE\n',
        f'PUBLIC CONST SERVICE=ADDRESS(${labels["sdx_probe_service"]:x})\nENDMODULE\n')
    config.write_text(text)
    require(labels['sdx_probe_stubs_end'] <= ABI['runtime']['guest_start'],
            'SDX guest code can alias bank-zero transition PCs')


def image(output):
    PIN=json.loads((ROOT/'toolchain/altirra-shell-paced.json').read_text())
    ROM=ROOT/'build/firmware/altirraos-816.rom'
    import hashlib
    require(hashlib.sha256(ROM.read_bytes()).hexdigest()==PIN['rom']['sha256'],
            'SDX ROM shadow requires the pinned ROM')
    runtime=ABI['runtime']
    state=bytearray(runtime['code_offset'])
    state[:0x4000]=ROM.read_bytes()
    base=runtime['resident_bank']*65536
    return [dict(address=base,bytes=list(state),writable=True,executable=False),
            dict(address=base+runtime['code_offset'],
                 bytes=list((Path(output)/'hosted.bin.sdx').read_bytes()),
                 writable=False,executable=True)]
