#!/usr/bin/env python3
"""Generate native limits for the bounded C application file ABI."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def files():
    abi=json.loads((ROOT/'abi/c-program.json').read_text())
    process=json.loads((ROOT/'abi/process.json').read_text())
    pairs=[('VERSION',str(abi['version'])),('FILE_MAGIC','LONGCARD($'+format(int.from_bytes(abi['magic'].encode(),'little'),'x')+')'),
           ('HEADER_BYTES',str(abi['header_bytes'])),('SEGMENT_LIMIT',str(abi['segment_limit'])),
           ('SPAN_LIMIT','LONGCARD('+str(abi['span_limit'])+')'),('FILE_LIMIT','LONGCARD('+str(abi['file_limit'])+')'),
           ('WORKSPACE_MASK',str(abi['stack_requirement']['workspace_mask'])),
           ('STACK_SHIFT',str(abi['stack_requirement']['shift'])),
           ('STACK_UNIT',str(abi['stack_requirement']['unit_bytes'])),
           ('LINK_BANK',str(abi['link_bank'])),('BANK_LIMIT',str(abi['max_banks']))]
    outputs = {ROOT/'lib/dos/c-program-abi.inc':'; Generated by tools/generate_c_program.py from abi/c-program.json.\n'+
            ''.join('PUBLIC CONST '+name+'='+value+'\n' for name,value in pairs),
            ROOT/'c/calypsi/program-flags.h':'/* Generated from abi/process.json; do not edit. */\n'+
            '#define EXEC_PROGRAM_STOP_PENDING '+str(process['break_flags']['PENDING'])+'\n'}

    entries=abi['dos_entries']
    outputs[ROOT/'c/calypsi/dos-entries.h']='/* Generated from abi/c-program.json; do not edit. */\n'+''.join(
        '#define C_DOS_'+e['name'].upper()+' '+str(i)+'\n' for i,e in enumerate(entries))+f'#define C_DOS_COUNT {len(entries)}\n'
    outputs[ROOT/'c/calypsi/dos-entries.inc']='; Generated from abi/c-program.json; do not edit.\n'+''.join(
        '  entries('+str(i)+')=ADDRESS(@'+e['native']+')\n' for i,e in enumerate(entries))
    return outputs

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,content in files().items():
        if args.check:
            if not path.exists() or path.read_text()!=content:raise SystemExit('Stale C program ABI: '+str(path))
        else:path.write_text(content)
