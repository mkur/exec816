#!/usr/bin/env python3
"""Extract the pinned GEM4XE text-origin arithmetic with explicit state."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PORT = ROOT/'ports/gem4xe/text'


def generate(source):
    pin = json.loads((PORT/'inputs.json').read_text())
    raw = (source/'src/vdi/vdi.c').read_bytes()
    assert hashlib.sha256(raw).hexdigest() == pin['files']['src/vdi/vdi.c']
    text = raw.decode().replace('\r\n', '\n')
    start = text.index('static WORD align_x(')
    end = text.index('/* One glyph', start)
    body = text[start:end].rstrip()
    body = body.replace('align_x(WORD x, WORD w)',
                        'GemTextAlignX(int32_t x, int32_t w, int16_t horizontal)')
    body = body.replace('align_y(WORD y)',
                        'GemTextAlignY(int32_t y, int16_t vertical)')
    body = body.replace('static WORD ', 'static int32_t ').replace('(WORD)', '(int32_t)')
    body = body.replace('vwk.h_align', 'horizontal').replace('vwk.v_align', 'vertical')
    body = re.sub(r'\bFONT_(HALF|ASCENT|H|TOP|DESCENT)\b',
                  lambda m: 'EXEC_VDI_FONT_'+('HEIGHT' if m[1] == 'H' else m[1]), body)
    return ('/* Generated by tools/generate_gem_text.py; do not edit.\n'
            ' * GEM4XE '+pin['revision']+' src/vdi/vdi.c; GPL-2.0-or-later.\n'
            ' * Explicit workstation state, widened origins and Exec font metrics. */\n'
            '#ifndef EXEC_GEM_TEXT_ORIGIN_H\n#define EXEC_GEM_TEXT_ORIGIN_H\n'
            '#include <stdint.h>\n#include <gem.h>\n#include <exec816/vdi-unit.h>\n'
            +body+'\n#endif\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT/'build/gem-vdi/upstream')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate(args.source)
    path = PORT/'origin.h'
    if args.check:
        assert path.read_text() == content, 'Stale GEM text origin'
    else:
        path.write_text(content)
