"""Pack immutable frame marks into both packed-pixel X phases at build time."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT/'lib/desktop/frame-gadgets.json'
VRAM = ROOT/'platform/altirraos/vbxe-vram.json'
NAMES = ('close', 'full', 'iconify', 'tile', 'up', 'down', 'size')
PITCH, ROWS = 16, 12
# Hardware indices for the existing GEM white, black and title-ink pens.
INK = {'.': 0, '#': 15, 'b': 12}


def packed():
    assets = json.loads(ASSETS.read_text())
    memory = json.loads(VRAM.read_text())
    region = next(r for r in memory['regions'] if r['name'] == 'frame_gadgets')
    assert set(assets) == set(NAMES)
    data = bytearray(); descriptors = []
    for name in NAMES:
        rows = assets[name]; width = len(rows[0]); height = len(rows)
        assert 0 < width <= 16 and 0 < height <= ROWS
        assert all(len(row) == width and set(row) <= INK.keys() for row in rows)
        descriptors.append((len(data), width, height))
        for phase in (0, 1):
            slot = bytearray(PITCH*ROWS)
            for y, row in enumerate(rows):
                for x, pixel in enumerate(row, phase):
                    slot[y*PITCH+x//2] |= INK[pixel] << (0 if x&1 else 4)
            data.extend(slot)
    assert len(data) <= region['capacity_bytes'] <= region['reserved_bytes']
    assert region['base']+region['reserved_bytes'] <= memory['bytes']
    for other in memory['regions']:
        if other is not region:
            assert (region['base'] >= other['base']+other['reserved_bytes'] or
                    region['base']+region['reserved_bytes'] <= other['base'])
    for other in memory['diagnostics']:
        assert (region['base'] >= other['base']+other['bytes'] or
                region['base']+region['reserved_bytes'] <= other['base'])
    assert sum(r['reserved_bytes'] for r in memory['regions']) == memory['reserved_bytes']
    assert memory['reserved_bytes']+memory['unassigned_bytes'] == memory['bytes']
    return region, bytes(data), descriptors


def generate(output):
    region, data, descriptors = packed()
    lines = ['/* Generated by tools/generate_frame_gadgets.py. Do not edit. */',
             '#ifndef GEM_FRAME_GADGETS_H', '#define GEM_FRAME_GADGETS_H',
             f'#define GEM_FRAME_GADGET_BASE {region["base"]}UL',
             f'#define GEM_FRAME_GADGET_PHASE {PITCH*ROWS}',
             'struct GemFrameImage { UWORD offset,width,height; };',
             'static const struct GemFrameImage GemFrameImages[]={']
    lines += ['    {%d,%d,%d},' % d for d in descriptors]
    lines += ['};', '__attribute__((section("gemtables"))) static const UBYTE GemFramePixels[]={']
    lines += ['    '+','.join(str(v) for v in data[i:i+16])+',' for i in range(0,len(data),16)]
    lines += ['};', '#endif']
    output.write_text('\n'.join(lines)+'\n')
    digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    return dict(generator_sha256=digest(Path(__file__)), assets_sha256=digest(ASSETS),
                vram_sha256=digest(VRAM), header_sha256=digest(output),
                image_bytes=len(data), descriptor_bytes=len(descriptors)*6,
                reserved_bytes=region['reserved_bytes'], base=region['base'])
