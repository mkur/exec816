#!/usr/bin/env python3
"""Generate the shared input.device wire records and upper-memory binding."""
import argparse
import json
from pathlib import Path

from generate_memory import ROOT, require
from generate_heap import write

ABI = json.loads((ROOT/'abi/input-device.json').read_text())
HEADER = '; Generated by tools/generate_input_device.py; do not edit.\n'
TYPES = {'u16': ('CARD', 'UWORD', 2, 2), 'u32': ('LONGCARD', 'ULONG', 4, 2),
         'IOStdReq': ('EXEC.IOStdReq', 'struct IOStdReq', 42, 2),
         'InputConfig': ('INPUT.Config', 'struct InputConfig', 32, 2)}


def validate():
    require(ABI['abi'] == 'exec816.input-device' and ABI['version'] == 1,
            'Unsupported input.device ABI')
    for name, record in ABI['records'].items():
        end = 0
        for field, kind, offset in record['fields']:
            _, _, size, alignment = TYPES[kind]
            end = (end+alignment-1)//alignment*alignment
            require(end == offset, 'Invalid input.device field: '+name+'.'+field)
            end += size
        require((end+1)//2*2 == record['bytes'], 'Invalid input.device size: '+name)
    require(ABI['fields']['BINDINGS']+ABI['constants']['OPEN_SLOTS']*96 <= ABI['fields']['SOURCES'],
            'Input binding/source overlap')
    require(ABI['fields']['SOURCES']+ABI['constants']['SOURCE_SLOTS']*92 <= ABI['state_bytes'],
            'Input state exceeds reserved arena')


def types():
    validate()
    text = HEADER+'MODULE INPUTDEVICE\nUSE EXEC\nUSE INPUT\n'
    text += ''.join(f'PUBLIC CONST {k}=${v:x}\n' for k, v in ABI['constants'].items())
    for name, record in ABI['records'].items():
        text += f'PUBLIC CONST {name.upper()}_BYTES={record["bytes"]}\n'
        text += 'PUBLIC TYPE '+name+'=[\n'+''.join(
            f'  {TYPES[kind][0]} {field}\n' for field, kind, _ in record['fields'])+']\n'
    return text+'ENDMODULE\n'


def c_header():
    validate()
    text = ('/* Generated by tools/generate_input_device.py; MIT public interface. */\n'
            '#ifndef DEVICES_INPUT_H\n#define DEVICES_INPUT_H\n'
            '#include <exec/io.h>\n#include <exec/input.h>\n')
    text += ''.join(f'#define INPUTDEV_{k} ({v}UL)\n' for k, v in ABI['constants'].items())
    text += ('/* entry is an Action native-v2 entry address, not a C function pointer.\n'
             ' * Handler arguments: ULONG context, borrowed far24 InputEvent pointer.\n'
             ' * The input Task owns the callback stack and DP. */\n')
    for name, record in ABI['records'].items():
        text += f'#define INPUTDEV_{name.upper()}_BYTES ({record["bytes"]})\n'
        text += '\nstruct InputDevice'+name+' {\n'+''.join(
            f'    {TYPES[kind][1]} {field};\n' for field, kind, _ in record['fields'])+'};\n'
    return text+'#endif\n'


def reserve_metadata(memory):
    if 'input_device_storage' in memory:
        return
    start = (memory['profile']['code_origin']+15)//16*16
    require(start+ABI['state_bytes'] < (memory['constants']['KERNEL_BANK']+1)*65536,
            'Input device metadata exceeds kernel bank')
    memory['upper_reservations'].append(dict(name='input-device', address=start, size=ABI['state_bytes']))
    memory['profile']['code_origin'] = start+ABI['state_bytes']
    memory['input_device_storage'] = dict(BASE=start, BYTES=ABI['state_bytes'])


def generate(output, memory):
    validate()
    require((ROOT/'lib/input/inputdevice.act').read_text() == types(), 'Stale input.device Action records')
    require((ROOT/'c/include/devices/input.h').read_text() == c_header(), 'Stale input.device C records')
    reserve_metadata(memory)
    base = memory['input_device_storage']['BASE']
    text = HEADER+'MODULE INPUTDEVICEMETA\n'+f'PUBLIC CONST BASE=${base:x}, BYTES={ABI["state_bytes"]}\n'
    text += ''.join(f'PUBLIC CONST {k}=${base+v:x}\n' for k, v in ABI['fields'].items())
    write(Path(output)/'inputdevicemeta.act', text+'ENDMODULE\n', False)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    write(ROOT/'lib/input/inputdevice.act', types(), args.check)
    write(ROOT/'c/include/devices/input.h', c_header(), args.check)
