"""Generate IDE Plus commands, hardware constants and resident metadata."""
import argparse,json
from pathlib import Path
from generate_memory import ROOT,require
from generate_heap import write
ABI=json.loads((ROOT/'abi/ideplus.json').read_text())
HEADER='; Generated by tools/generate_ideplus.py; do not edit.\n'
def types():
    geometry=ABI['records']['Geometry']
    require(geometry['size']==12 and geometry['alignment']==2,'Unsupported geometry size')
    cursor=0
    for name,kind,offset in geometry['fields']:
        require(offset==cursor,'Invalid geometry offset: '+name)
        cursor+={'CARD':2,'LONGCARD':4}[kind]
    require(cursor==geometry['size'],'Invalid geometry size')
    record='PUBLIC TYPE Geometry=[\n'+''.join(f'  {kind} {name}\n' for name,kind,_ in geometry['fields'])+']\n'
    return HEADER+'MODULE IDEPLUS\n'+''.join(f'PUBLIC CONST {k}={v}\n' for k,v in ABI['constants'].items())+record+'ENDMODULE\n'
def assembly():
    return HEADER+''.join(f'IP_{k} = ${v:x}\n' for k,v in ABI['constants'].items())
def reserve_metadata(memory):
    start=(memory['profile']['code_origin']+15)//16*16
    require(start+1024 < (memory['constants']['KERNEL_BANK']+1)*65536,'IDE metadata exceeds kernel bank')
    memory['upper_reservations'].append(dict(name='ideplus-resident',address=start,size=1024))
    memory['profile']['code_origin']=start+1024
    memory['ideplus_storage']=dict(BASE=start,BYTES=1024)
def generate(output,memory):
    require((ROOT/'lib/io/ideplus.act').read_text()==types(),'Stale IDE Plus definitions')
    require((ROOT/'platform/altirraos/ideplus.inc').read_text()==assembly(),'Stale IDE Plus assembly')
    base=memory['ideplus_storage']['BASE']
    text=HEADER+'MODULE IDEMETA\n'+f'PUBLIC CONST BASE=${base:x}\n'
    text+=''.join(f'PUBLIC CONST {k}=${base+v:x}\n' for k,v in ABI['fields'].items())
    write(Path(output)/'idemeta.act',text+'ENDMODULE\n',False)
    write(Path(output)/'ideplus-storage.inc',HEADER+
          f'IP_META_BUS = ${base+ABI["fields"]["BUS"]:x}\n'+
          f'IP_PROBE = ${base+768:x}\n',False)
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    write(ROOT/'lib/io/ideplus.act',types(),a.check)
    write(ROOT/'platform/altirraos/ideplus.inc',assembly(),a.check)
