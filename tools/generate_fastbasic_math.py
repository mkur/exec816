#!/usr/bin/env python3
"""Adapt the pinned Altirra decimal math source from MADS to relocatable ca65.

The original notice and instruction order remain in the generated source.
Only assembler syntax, symbolic relocation and guest-D addressing change.
"""
import argparse
from decimal import Decimal, localcontext, ROUND_HALF_UP
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
ENTRIES = dict(AFP='afp', FASC='fasc', IFP='ipf', FPI='fpi', ZFR0='zfr0',
               ZF1='zf1', FSUB='fsub', FADD='fadd', FMUL='fmul', FDIV='fdiv',
               PLYEVL='plyevl', FLD0R='fld0r', FLD0P='fld0p', FLD1R='fld1r',
               FLD1P='fld1p', FST0R='fst0r', FST0P='fst0p', FMOVE='fmove',
               EXP='exp', EXP10='exp10', LOG='log', LOG10='log10',
               FPNORM='fp_normalize', FPHALF='fpconst_half', ATNCOEF='atncoef')


def number(text):
    with localcontext() as context:
        context.prec = 80
        value = Decimal(text)
        sign = 0x80 if value < 0 else 0
        value = abs(value)
        if not value:
            return bytes(6)
        exponent = value.adjusted() // 2
        mantissa = int((value / Decimal(100)**exponent * 100**4)
                       .to_integral_value(rounding=ROUND_HALF_UP))
        if mantissa >= 100**5:
            exponent += 1
            mantissa //= 100
        pairs = []
        for _ in range(5):
            pair = mantissa % 100
            pairs.append((pair // 10)*16+pair % 10)
            mantissa //= 100
        return bytes([sign | (exponent+64), *reversed(pairs)])


def adapt(path):
    source = path.read_text().replace('\r\n', '\n')
    # ca65 cannot forward-reference a scope. Flatten MADS procedure-local
    # names deterministically while preserving its lexical name resolution.
    scopes = {}
    scope = None
    for line in source.splitlines():
        code = line.partition(';')[0].strip().replace('.nowarn ', '')
        if code.startswith('.proc '):
            scope = code.split()[1]
            scopes[scope] = set()
        elif code == '.endp':
            scope = None
        elif scope:
            match = re.match(r'([A-Za-z_]\w*)(?::|\s*=)', code)
            if match and match[1] not in ('smi','scc'):
                scopes[scope].add(match[1])
    header = '''; Generated by tools/generate_fastbasic_math.py; edit the generator.
; Input: pinned mini65 asm/mathpack.s; original notice follows.
.setcpu "65816"
.a8
.i8
.feature force_range
.include "fastbasic.inc"
fr0=$d4
_fr3=$da
fr1=$e0
fr2=$e6
cix=$f2
inbuff=$f3
ztemp4=$f7
flptr=$fc
fptr2=$fe
lbuff=$580
plyarg=$5e0
fpscr=$5e6
.segment "RUNTIME"
.align $100
fb_math_base:
'''
    lines = [header]
    repeat = False
    skip = False
    scope = None
    for original in source.splitlines():
        code, mark, comment = original.partition(';')
        s = code.strip()
        if s.startswith('.macro'):
            skip = True
        if skip:
            if s == '.endm':
                skip = False
            continue
        s = s.replace('.nowarn ', '')
        if s.startswith('.proc '):
            scope = s.split()[1]
            s = scope+':'
        elif s == '.endp':
            scope = None
            s = ''
        else:
            s = re.sub(r'([A-Za-z_]\w*)\.([A-Za-z_]\w*)', r'mp_\1_\2', s)
            if scope and not s.startswith('.def :'):
                s = re.sub(r'\b[A-Za-z_]\w*\b',
                           lambda m: f'mp_{scope}_{m[0]}' if m[0] in scopes[scope] else m[0], s)
        if s.startswith(('org', 'fixadr', 'ckaddr')):
            operation, address = s.split(None, 1)
            base, _, subtract = address.partition('-')
            offset = int(base.replace('$', '0x'), 0)-int(subtract or '0')-0xd800
            if operation == 'org':
                s = ''
            elif operation == 'fixadr':
                s = f'.res ${offset:x}-(*-fb_math_base), $ea'
            else:
                s = f'.assert *-fb_math_base=${offset:x}, error, "Math entry offset"'
        elif s.startswith('.def :'):
            s = s[len('.def :'):].replace(' = *', ':')
            if not s.endswith(':'):
                s += ':'
        elif s.startswith('.fl'):
            s = '.byte '+','.join(f'${v:02x}' for v in number(s.split(None, 1)[1]))
        elif s.startswith('.pages'):
            s = 'fb_constants_start:'
        elif s == '.endpg':
            s = '.assert >fb_constants_start=>(* - 1), lderror, "Math constants page"'
        elif s.startswith('.rept'):
            s = '.repeat '+s.split()[1]+', mp_index'
            repeat = True
        elif s == '.endr':
            s = '.endrepeat'
            repeat = False
        elif re.match(r':\d+\s+dta', s):
            count, expression = s[1:].split('dta')
            expression = expression.strip().replace('[', '(').replace(']', ')').replace('#', 'mp_index')
            s = f'.repeat {count.strip()}, mp_index\n.byte {expression}\n.endrepeat'
        elif s.startswith('dta'):
            data = s[3:].strip()
            s = '.byte $2c' if data == '{bit $0100}' else '.byte '+data
        elif s.startswith('mwa'):
            s = 'lda #<lbuff\nsta inbuff\nlda #>lbuff\nsta inbuff+1'
        elif s.startswith('mva'):
            match = re.fullmatch(r'mva\s+(\S+)\s+(\S+)', s)
            s = f'lda {match[1]}\nsta {match[2]}'
        elif s.startswith('smi:'):
            s = 'bmi :+\n'+s[4:]+'\n:'
        elif s.startswith('scc:'):
            s = 'bcc :+\n'+s[4:]+'\n:'
        if repeat:
            s = s.replace('-#', '-mp_index')
        if ',y+' in s:
            s = s.replace(',y+', ',y')+'\niny'
        # Absolute,Y on FR0/FR1 would use the guest bank, not relocated D.
        for register, slot in [('fr0+1', 3), ('fr1+1', 9), ('fr0', 0), ('fr1', 6)]:
            s = re.sub(r'(?m)^(lda|sta|adc|sbc)\s+'+re.escape(register)+r',y$',
                       rf'\1 [FB_MATH_POINTERS+{slot}],y', s)
        # This internal entry loads from a D offset, not a guest-bank pointer.
        s = s.replace('jmp\t\tfld0r_zp', 'jmp fb_fld0r_zp')
        lines.append(s + (' ;'+comment if mark else ''))
    lines += ['.assert *-fb_math_base=$800, error, "Math package size"',
              '.export fb_math_base, fb_math_end', 'fb_math_end:']
    for name, symbol in ENTRIES.items():
        lines += [f'.export fb_{name.lower()}', f'fb_{name.lower()}={symbol}']
    lines += ['''; Internal FLD0R from the relocated direct page; preserves X and carry.
fb_fld0r_zp:
    stx FB_MATH_POINTERS+12
    ldy #5
loop:
    lda [FB_MATH_POINTERS+12],y
    sta [FB_MATH_POINTERS],y
    dey
    bpl loop
    rts
''']
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT/'build/fastbasic/upstream/testsuite/mini65/asm/mathpack.s')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT/'ports/fastbasic/target/mathpack.asm'
    result = adapt(args.source)
    if args.check:
        if output.read_text() != result:
            raise SystemExit('Stale FastBasic math adaptation')
    else:
        output.write_text(result)
