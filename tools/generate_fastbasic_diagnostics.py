#!/usr/bin/env python3
"""Generate the fixed diagnostic file and compiler registration constants."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]


def files():
    a=json.loads((ROOT/'abi/fastbasic-diagnostics.json').read_text())
    values=dict(MAGIC=int.from_bytes(a['magic'].encode(),'little'),VERSION=a['version'],
        BYTES=a['bytes'],SOURCE_CAPACITY=a['source_capacity'],MESSAGE_CAPACITY=a['message_capacity'])
    values.update({'FIELD_'+n.upper():v for n,v in a['fields'].items()})
    values.update({'STAGE_'+n.upper():v for n,v in a['stages'].items()})
    values.update({'REGISTER_'+n.upper():v*2 for n,v in a['registration_words'].items()})
    values['REGISTER_BYTES']=len(a['registration_words'])*2
    action='; SPDX-License-Identifier: MIT\n; Generated by tools/generate_fastbasic_diagnostics.py.\nMODULE FBDIAGABI\n'
    action+=''.join('PUBLIC CONST '+n+'='+('LONGCARD($%x)'%v if v>65535 else str(v))+'\n' for n,v in values.items())
    header='/* SPDX-License-Identifier: MIT\n * Generated by tools/generate_fastbasic_diagnostics.py. */\n#ifndef EXEC816_FASTBASIC_DIAGNOSTIC_H\n#define EXEC816_FASTBASIC_DIAGNOSTIC_H\n#include <exec/types.h>\n'
    header+=''.join('#define FBD_'+n+' '+('0x%xUL'%v if v>65535 else str(v))+'\n' for n,v in values.items())
    header+='''struct ExecFastBasicDiagnostic {
    UBYTE magic[4];
    UWORD version,bytes;
    ULONG job;
    UWORD stage,basic_error;
    LONG native_cause;
    ULONG line;
    UWORD byte_column,source_bytes,message_bytes,reserved;
    char source[128],message[64];
};
/* Pure reader: no Process, I/O or ownership side effects. */
WORD ExecFastBasicDiagnosticMatches(const struct ExecFastBasicDiagnostic *,
    ULONG bytes,ULONG job,CONST_STRPTR source);
#endif
'''
    return {ROOT/'lib/dos/fbdiagabi.act':action+'ENDMODULE\n',
        ROOT/'c/include/exec816/fastbasic-diagnostic.h':header}


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,text in files().items():
        if a.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit('Stale generated file: '+str(path))
        else:path.write_text(text)
