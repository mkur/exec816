#!/usr/bin/env python3
"""Port-local declarations selected from the already pinned GEM reference."""
import argparse,hashlib,json,re,urllib.request
from pathlib import Path
from native_program import ROOT,require,sha256
PIN=ROOT/'ports/gem4xe/aes-binding-inputs.json'
TARGET=ROOT/'ports/gem4xe/apps/qed/native/qed-gem-extra.h'

def generate(source):
    pin=json.loads(PIN.read_text())
    source=Path(source)
    if not source.exists():
        url='https://raw.githubusercontent.com/slaapliedje/gem4xe/'+pin['revision']+'/src/app/gem.h'
        with urllib.request.urlopen(url,timeout=30) as response:payload=response.read()
        require(hashlib.sha256(payload).hexdigest()==pin['files']['src/app/gem.h'],
                'Changed GEM declaration download')
        source.parent.mkdir(parents=True,exist_ok=True);source.write_bytes(payload)
    require(sha256(source)==pin['files']['src/app/gem.h'],'Changed GEM declaration reference')
    text=re.sub(r'/\*.*?\*/','',source.read_text(),flags=re.S)
    public='\n'.join(p.read_text() for p in (ROOT/'c/include').rglob('*.h'))
    known_macros=set(re.findall(r'^\s*#define\s+(\w+)',public,flags=re.M))
    known_functions=set(re.findall(r'\b(\w+)\s*\([^;{}]*\)\s*;',public))
    macros=[]
    for line in text.replace('\\\n',' ').splitlines():
        m=re.match(r'\s*#define\s+(\w+)(.*)',line)
        if m and m[1] not in known_macros and m[1]!='GEM4XE_APP_GEM_H':
            if not m[2].startswith('('):
                macros.append('#ifndef '+m[1]+'\n#define '+m[1]+m[2]+'\n#endif')
    types=[]
    for start in re.finditer(r'\btypedef\b',text):
        depth=0
        for at in range(start.end(),len(text)):
            if text[at]=='{':depth+=1
            elif text[at]=='}':depth-=1
            elif text[at]==';' and depth==0:
                block=text[start.start():at+1];name=re.search(r'(\w+)\s*;$',block)[1]
                if name in {'VdiHdl','PARMBLK','USERBLK','EVNTREC','MN_SET'}:types.append(block)
                break
    plain=re.sub(r'^\s*#.*','',text,flags=re.M)
    functions=[]
    for part in plain.split(';'):
        part=part.strip();m=re.search(r'\b(\w+)\s*\(',part)
        if not m or '{' in part or '}' in part or part.startswith('typedef'):continue
        name=m[1]
        if name in known_functions:continue
        if not (name.startswith(('appl_','evnt_','graf_','form_','objc_','menu_','wind_',
                                  'rsrc_','shel_','scrp_','v_','vs','vq','vr','rc_'))):continue
        functions.append(' '.join(part.replace(' FAR','').split())+';')
    result=('/* Generated by tools/generate_qed_compat.py.\n'
        ' * Declarations/constants adapted from pinned GEM4XE gem.h (LGPL-2.1-or-later).\n'
        ' * Public Exec records stay authoritative; no donor gateway/runtime is imported. */\n'
        '#ifndef QED_GEM_EXTRA_H\n#define QED_GEM_EXTRA_H\n'+
        '\n'.join(types+macros+functions)+'\n#endif\n')
    return '\n'.join(line.rstrip() for line in result.splitlines())+'\n'

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--reference',type=Path,default=ROOT/'build/qed-sources/gem-reference/gem.h')
    p.add_argument('--check',action='store_true');a=p.parse_args();content=generate(a.reference)
    if a.check:require(TARGET.read_text()==content,'Stale QED GEM declarations')
    else:TARGET.write_text(content)
