#!/usr/bin/env python3
"""Reproduce the selected GEM4XE raster algorithms without its machine ABI."""
import argparse
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
PORT = ROOT/'ports/gem4xe/raster'


def generate(source, fetch=False):
    pin = json.loads((PORT/'inputs.json').read_text())
    inputs = {}
    for name, digest in pin['files'].items():
        path = source/name
        if not path.exists() and fetch:
            url = pin['repository'].replace('github.com', 'raw.githubusercontent.com')
            with urllib.request.urlopen(url+'/'+pin['revision']+'/'+name, timeout=30) as r:
                data = r.read()
            if hashlib.sha256(data).hexdigest() != digest:
                raise ValueError('Changed raster download: '+name)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError('Changed raster input: '+name)
        inputs[name] = data.decode().replace('\r\n', '\n')
    header = inputs['src/vdi/vdidev.h']
    op = header[header.index('static __inline WORD rop4('):header.index('/* ---- the table')]
    op = op.replace('static __inline WORD rop4(', 'static int16_t GemRasterOp(')
    op = op.replace('WORD', 'int16_t')
    device = inputs['src/vdi/dev_vbxe.c']
    first = device.index('                if (s == d) {', device.index('static void copy_rows('))
    last = device.index('                span_io(dr +', first)
    merge = device[first:last]
    merge = '\n'.join(line[16:] if line.startswith(' '*16) else line for line in merge.splitlines())+'\n'
    merge = merge.replace('rop4(', 'GemRasterOp(').replace('UWORD', 'uint16_t').replace('WORD', 'int16_t')
    recipes = device[device.index('#define ROPC('):device.index('static WORD rop_blit(')]
    recipes = recipes.replace('rop_code[16]', 'GemRasterRecipes[16]').replace(' FAR ', ' ')
    for old, value in [('BLT_MODE_COPY','0'),('BLT_MODE_OR','3'),('BLT_MODE_AND','4'),('BLT_MODE_XOR','5')]:
        recipes = recipes.replace(old,value)
    return ('/* Generated by tools/generate_gem_raster.py; do not edit.\n'
        ' * Selected from GEM4XE '+pin['revision']+'.\n'
        ' * GPL-2.0-or-later; see inputs.json and upstream COPYING.\n'
        ' * Adaptations: explicit mode and row buffers; fixed-width huge-data C. */\n'
        '#ifndef EXEC_GEM_RASTER_CORE_H\n#define EXEC_GEM_RASTER_CORE_H\n#include <stdint.h>\n'+op+
        'static void GemRasterMerge(uint8_t *row_dst,const uint8_t *row_src,\n'
        '    uint16_t s,uint16_t d,int16_t n,int16_t m)\n{\n    uint16_t k;\n'+
        '\n'.join('    '+line for line in merge.splitlines())+'\n}\n'+recipes+
        '#undef ROPC\n#endif\n')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=ROOT/'build/gem-raster/upstream')
    p.add_argument('--fetch', action='store_true')
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    output = PORT/'core.h'
    content = generate(a.source, a.fetch)
    if a.check:
        if output.read_text() != content:raise SystemExit('Stale GEM raster core')
    else:output.write_text(content)
