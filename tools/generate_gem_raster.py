#!/usr/bin/env python3
"""Reproduce the selected GEM4XE raster algorithms without its machine ABI."""
import argparse
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
PORT = ROOT/'ports/gem4xe/raster'


def inputs(source, fetch=False):
    pin = json.loads((PORT/'inputs.json').read_text())
    inputs = {}
    for name, digest in pin['files'].items():
        path = source/name
        if not path.exists() and fetch:
            url = pin['repository'].replace('github.com', 'raw.githubusercontent.com')
            with urllib.request.urlopen(url+'/'+pin['revision']+'/'+name, timeout=30) as r:
                data = r.read()
            if hashlib.sha256(data).hexdigest() != digest:
                raise ValueError('Changed raster download: '+name)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError('Changed raster input: '+name)
        inputs[name] = data.decode().replace('\r\n', '\n')
    return pin,inputs


def generate(source, fetch=False):
    pin,selected=inputs(source,fetch)
    header = selected['src/vdi/vdidev.h']
    op = header[header.index('static __inline WORD rop4('):header.index('/* ---- the table')]
    op = op.replace('static __inline WORD rop4(', 'static int16_t GemRasterOp(')
    op = op.replace('WORD', 'int16_t')
    device = selected['src/vdi/dev_vbxe.c']
    first = device.index('                if (s == d) {', device.index('static void copy_rows('))
    last = device.index('                span_io(dr +', first)
    merge = device[first:last]
    merge = '\n'.join(line[16:] if line.startswith(' '*16) else line for line in merge.splitlines())+'\n'
    merge = merge.replace('rop4(', 'GemRasterOp(').replace('UWORD', 'uint16_t').replace('WORD', 'int16_t')
    first=device.index('            if (((sx ^ dx) & 1) == 0)',last)
    last=device.index('            span_io(dr +',first)
    copy='\n'.join(line[12:] if line.startswith(' '*12) else line for line in device[first:last].splitlines())
    copy=copy.replace('((sx ^ dx) & 1) == 0','s == d').replace('dx & 1','d').replace('sx & 1','s')
    copy=copy.replace('dx + n','d + n').replace('nib_shift(', 'GemRasterShift(')
    copy=copy.replace('uint8_t first = row_dst[0], last = row_dst[dn - 1];',
        'uint8_t first = d ? row_dst[0] : 0, last = ((d + n) & 1) ? row_dst[dn - 1] : 0;')
    recipes = device[device.index('#define ROPC('):device.index('static WORD rop_blit(')]
    recipes = recipes.replace('rop_code[16]', 'GemRasterRecipes[16]').replace(' FAR ', ' ')
    for old, value in [('BLT_MODE_COPY','0'),('BLT_MODE_OR','3'),('BLT_MODE_AND','4'),('BLT_MODE_XOR','5')]:
        recipes = recipes.replace(old,value)
    return ('/* Generated by tools/generate_gem_raster.py; do not edit.\n'
        ' * Selected from GEM4XE '+pin['revision']+'.\n'
        ' * GPL-2.0-or-later; see inputs.json and upstream COPYING.\n'
        ' * Adaptations: explicit mode and row buffers; fixed-width huge-data C. */\n'
        '#ifndef EXEC_GEM_RASTER_CORE_H\n#define EXEC_GEM_RASTER_CORE_H\n#include <stdint.h>\n#include <string.h>\n'+op+
        '#ifdef __CALYPSI_CORE_65816__\n'
        'extern void GemRasterShift(uint8_t *,const uint8_t *,uint16_t);\n'
        '#else\nstatic void GemRasterShift(uint8_t *dst,const uint8_t *src,uint16_t n)\n{\n'
        '    uint16_t i;\n    for (i=0;i<n;++i) dst[i]=(uint8_t)((src[i]<<4)|(src[i+1]>>4));\n}\n#endif\n\n'
        '/* Private row buffers include one spare source byte for the final shift. */\n'
        'static void GemRasterCopy(uint8_t *row_dst,const uint8_t *row_src,\n'
        '    uint16_t s,uint16_t d,uint16_t n)\n{\n'
        '    uint16_t dn=(d+n+1)>>1;\n    if (!n) return;\n'+
        '\n'.join(('    '+line).rstrip() for line in copy.splitlines())+'\n}\n\n'+
        'static void GemRasterMerge(uint8_t *row_dst,const uint8_t *row_src,\n'
        '    uint16_t s,uint16_t d,int16_t n,int16_t m)\n{\n    uint16_t k;\n'+
        '    if (m==3) { GemRasterCopy(row_dst,row_src,s,d,(uint16_t)n);return; }\n'+
        '\n'.join('    '+line for line in merge.splitlines())+'\n}\n'+recipes+
        '#undef ROPC\n#endif\n')


def generate_shift(source,fetch=False):
    pin,selected=inputs(source,fetch)
    donor=selected['src/vdi/nibs.s']
    body=donor[donor.index('              ldy     ##0'):donor.index(';;; text_row:')]
    body=body[:body.index(';;; ---------------------------------------------------------------------------')].rstrip()+'\n'
    body=body.replace('(dp:.tiny ns_src),y','[dp:.tiny (_Dp+4)],y')
    body=body.replace('(dp:.tiny ns_dst),y','[dp:.tiny _Dp],y')
    return ('; Generated by tools/generate_gem_raster.py; do not edit.\n'
        '; GEM4XE '+pin['revision']+' src/vdi/nibs.s; GPL-2.0-or-later.\n'
        '; Huge-data ABI: count in A16, destination in _Dp+0..3, source in _Dp+4..7.\n'
        '; Clobbers A/X/Y and flags; preserves D, DBR, S and callee-saved DP.\n'
        '; Up to 320 bytes, from 321 source bytes; long-indexed loads cross banks.\n'
        '              .rtmodel version,"1"\n              .rtmodel codeModel,"large"\n'
        '              .rtmodel dataModel,"huge"\n              .rtmodel core,"65816"\n'
        '              .extern _Dp\n              .public GemRasterShift\n'
        '              .section farcode,text\nGemRasterShift:\n'
        '              tax\n              beq     9$\n'+body)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=ROOT/'build/gem-raster/upstream')
    p.add_argument('--fetch', action='store_true')
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    for name,content in (('core.h',generate(a.source,a.fetch)),('shift.s',generate_shift(a.source,a.fetch))):
        output=PORT/name
        if a.check:
            if output.read_text() != content:raise SystemExit('Stale GEM raster '+name)
        else:output.write_text(content)
