#!/usr/bin/env python3
"""Generate the shared GEM object, frame geometry and drawing bridge records."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ABI = json.loads((ROOT / 'abi/gem-objects.json').read_text())


def layout():
    sizes = {'INT': (2, 2), 'CARD': (2, 2), 'LONGCARD': (4, 2)}
    result = {}
    for name, record in ABI['records'].items():
        offset, offsets = 0, {}
        for field, kind, cfield, *counts in record['fields']:
            size, align = sizes[kind]
            count = ABI['constants'].get(counts[0], counts[0]) if counts else 1
            offset = (offset + align - 1) // align * align
            offsets[field] = offset
            offset += size * count
        offset = (offset + 1) // 2 * 2
        result[name] = dict(size=offset, alignment=2, fields=offsets)
        sizes[name] = offset, 2
    return result


def files():
    action = ['; Generated by tools/generate_gem_objects.py; do not edit.',
              'MODULE GEMOBJECTS']
    header = ['/* Generated by tools/generate_gem_objects.py; do not edit. */',
              '#ifndef GEM_GEOMETRY_H', '#define GEM_GEOMETRY_H',
              '#include <exec/types.h>', '#pragma pack(push, 2)']
    action += [f'PUBLIC CONST {n}={v}' for n, v in ABI['constants'].items()]
    header += [f'#define GEM_{n} {v}' for n, v in ABI['constants'].items()]
    ctypes = {'INT': 'WORD', 'CARD': 'UWORD', 'LONGCARD': 'ULONG'}
    for name, record in ABI['records'].items():
        action += [f'PUBLIC TYPE {name}=[']
        header += ['typedef struct {']
        for field, kind, cfield, *counts in record['fields']:
            action += [f'  {kind}'+(' ARRAY' if counts else '')+f' {field}'+
                       (f'({counts[0]})' if counts else '')]
            header += [f'    {ctypes[kind]} {cfield}'+
                       (f'[GEM_{counts[0]}]' if counts else '')+';']
        action += [']']
        header += [f'}} {record["c_type"]};']
        ctypes[name] = record['c_type']
        for key, value in {f'{name.upper()}_SIZE': layout()[name]['size'],
                           **{f'{name.upper()}_OFFSET_{f.upper()}': o
                              for f, o in layout()[name]['fields'].items()}}.items():
            action += [f'PUBLIC CONST {key}={value}']
            header += [f'#define GEM_{key} {value}']
    action += ['ENDMODULE', '']
    header += ['#pragma pack(pop)', '#endif', '']
    return {ROOT/'lib/aes/gemobjects.act': '\n'.join(action),
            ROOT/'c/include/gem/geometry.h': '\n'.join(header)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Stale GEM geometry: '+str(path))
        else:
            path.write_text(content)
