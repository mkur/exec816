#!/usr/bin/env python3
"""Generate the common C runtime invocation and allocation layout."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ABI=json.loads((ROOT/'abi/c-runtime.json').read_text())


def expected_layout():
    return [(name+' size',record['bytes']) for name,record in ABI['records'].items()]+[
        (name+' '+field,offset) for name,record in ABI['records'].items()
        for field,kind,offset in record['fields']]+[('size_t bytes',2),('entry bytes',4)]


def files():
    lines=['/* SPDX-License-Identifier: MIT',
           ' * Generated by tools/generate_c_runtime.py; do not edit. */',
           '#ifndef EXEC816_C_RUNTIME_H','#define EXEC816_C_RUNTIME_H',
           '#include <exec/types.h>',f'#define EXEC_CRT_VERSION {ABI["version"]}']
    native=['; Generated from abi/c-runtime.json; MIT interface definitions.']
    for group,prefix in [('phases',''),('states','STATE_'),('flags','FLAG_'),('limits','')]:
        for name,value in ABI[group].items():
            symbol='EXEC_CRT_'+prefix+name
            lines.append(f'#define {symbol} {value}'+('UL' if value>32767 else ''))
            native.append(f'PUBLIC CONST {symbol}={value}')
    for name,record in ABI['records'].items():
        lines += [f'struct ExecCRuntime{name} {{',
                  *[f'    {kind} {field};' for field,kind,offset in record['fields']],'};']
        native.append(f'PUBLIC CONST EXEC_CRT_{name.upper()}_BYTES={record["bytes"]}')
        native += [f'PUBLIC CONST EXEC_CRT_{name.upper()}_{field.upper()}={offset}'
                   for field,kind,offset in record['fields']]
    lines += ['typedef LONG (*ExecCRuntimeEntry)(struct ExecCRuntimeCall *);',
              'LONG __exec_c_runtime_entry(struct ExecCRuntimeCall *);','#endif','']
    layout=['/* Generated by tools/generate_c_runtime.py; target-emitted ABI probe. */',
            '#include <exec816/c-runtime.h>','#include <stddef.h>',
            '__attribute__((section("exec_layout")))',
            'const UWORD ExecCRuntimeLayout[]={']
    layout += [f'    sizeof(struct ExecCRuntime{name}),' for name in ABI['records']]
    layout += [f'    offsetof(struct ExecCRuntime{name},{field}),'
               for name,record in ABI['records'].items() for field,kind,offset in record['fields']]
    layout += ['    sizeof(size_t),','    sizeof(ExecCRuntimeEntry),','};','']
    return {ROOT/'c/include/exec816/c-runtime.h':'\n'.join(lines),
            ROOT/'lib/dos/c-runtime-abi.inc':'\n'.join(native)+'\n',
            ROOT/'c/runtime/layout.c':'\n'.join(layout)}


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,content in files().items():
        if args.check:
            if not path.exists() or path.read_text()!=content:raise SystemExit('Stale C runtime ABI: '+str(path))
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
