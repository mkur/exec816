#!/usr/bin/env python3
"""Generate the ordinary SIO library interface used by native/loadable clients."""
import argparse
import json
import re
from generate_memory import ROOT, require
from generate_heap import write
from generate_io import SIO, SIO_CONSTANTS

ABI = json.loads((ROOT / 'abi/sio-client.json').read_text())


def interface():
    require(ABI['module'] == 'SIO' and ABI['implementation'] == 'SIOCLIENT' and
            ABI['abi'] == 'action65816.native.v2', 'Invalid SIO client identity')
    text = '; Generated by tools/generate_sio_client.py; do not edit.\nMODULE SIO\n'
    constants = {**SIO_CONSTANTS, **{'SIO_PROFILE_' + k: v for k, v in SIO['profiles'].items()}}
    text += ''.join(f'PUBLIC CONST {k}={v}\n' for k, v in constants.items())
    text += ''.join(f'PUBLIC CONST {k}={v}\n' for k, v in ABI['constants'].items())
    widths = {'BYTE': (1, 1), 'CARD': (2, 2), 'LONGCARD': (4, 2), 'BYTE POINTER': (3, 1)}
    for name, record in ABI['records'].items():
        text += f'PUBLIC CONST {name.upper()}_BYTES={record["size"]}\nPUBLIC TYPE {name}=[\n'
        cursor = 0
        for kind, field, offset in record['fields']:
            array = re.fullmatch(r'BYTE\[(\d+)\]', kind)
            size, alignment = (int(array[1]), 1) if array else widths[kind]
            cursor = (cursor + alignment - 1) // alignment * alignment
            require(cursor == offset, 'Invalid SIO client field: ' + field)
            cursor += size
            text += f'  BYTE ARRAY {field}({size})\n' if array else f'  {kind} {field}\n'
        require((cursor + 1) // 2 * 2 == record['size'], 'Invalid SIO client record size')
        text += ']\n'
    for name, spec in ABI['providers'].items():
        kind = 'PROC' if spec['result'] == 'PROC' else spec['result'] + ' FUNC'
        text += f'PUBLIC EXTERNAL {kind} {name}(' + ' '.join(k + ' ' + n for k, n in spec['arguments']) + ')\n'
    return text + 'ENDMODULE\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    write(ROOT / 'lib/io/sio.act', interface(), parser.parse_args().check)
