#!/usr/bin/env python3
"""Generate the selected FujiNet byte protocol, independent of native layouts."""
import argparse
import json
from pathlib import Path
from generate_memory import ROOT, require
from generate_heap import write

ABI = json.loads((ROOT / 'abi/fujinet.json').read_text())


def constants(abi=ABI):
    require(abi['abi'] == 'exec816.fujinet-control' and abi['revision'] == 1,
            'Unsupported FujiNet protocol')
    c = abi['constants']
    require(c['HOST_TABLE_BYTES'] == c['SLOTS'] * c['HOST_BYTES'] and
            c['DISK_TABLE_BYTES'] == c['SLOTS'] * c['DISK_BYTES'],
            'Invalid FujiNet slot table extents')
    require(c['DISK_FILE'] + c['DISPLAY_FILE_BYTES'] == c['DISK_BYTES'] and
            c['ADAPTER_VERSION'] + c['ADAPTER_VERSION_BYTES'] == c['ADAPTER_BYTES'],
            'Invalid FujiNet byte fields')
    commands = [v for k, v in c.items() if k.startswith('CMD_')]
    require(len(commands) == len(set(commands)) and all(0 <= v <= 255 for v in commands),
            'Invalid FujiNet commands')
    return c


def generate(check=False):
    c = constants()
    text = '; Generated by tools/generate_fujinet.py; do not edit.\nMODULE FUJINET\n'
    text += ''.join(f'PUBLIC CONST {key}={value}\n' for key, value in c.items())
    write(ROOT / 'lib/io/fujinet.act', text + 'ENDMODULE\n', check)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
