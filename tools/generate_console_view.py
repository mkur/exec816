#!/usr/bin/env python3
"""Public pointer-free console snapshots and input packets."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ABI = json.loads((ROOT/'abi/console-view.json').read_text())
WIDTHS = {'BYTE': (1, 1, 'UBYTE'), 'CARD': (2, 2, 'UWORD'),
          'LONGCARD': (4, 2, 'ULONG')}


def layout():
    result = {}
    for name, fields in ABI['records'].items():
        cursor = 0
        offsets = {}
        for field, kind, *count in fields:
            size, align, _ = WIDTHS[kind]
            cursor = (cursor+align-1)//align*align
            offsets[field] = cursor
            cursor += size*(count[0] if count else 1)
        result[name] = dict(size=(cursor+1)//2*2, fields=offsets)
    return result


def files():
    action = ['; Generated by tools/generate_console_view.py; do not edit.',
              'MODULE CONSOLEVIEWTYPES']
    header = ['/* Generated by tools/generate_console_view.py; do not edit. */',
              '#ifndef EXEC816_CONSOLE_VIEW_TYPES_H',
              '#define EXEC816_CONSOLE_VIEW_TYPES_H', '#include <exec/types.h>']
    constants = {'VERSION': ABI['version'], **ABI['constants']}
    for name, record in layout().items():
        constants[name.upper()+'_SIZE'] = record['size']
    for name, value in constants.items():
        action.append(f'PUBLIC CONST {name}={value}')
        header.append(f'#define EXEC_CONSOLE_VIEW_{name} {value}')
    for name, fields in ABI['records'].items():
        action.append('PUBLIC TYPE '+name+'=[')
        header.append('struct ExecConsoleView'+name+' {')
        for field, kind, *count in fields:
            action.append(f'  {kind} '+(f'ARRAY {field}({count[0]})' if count else field))
            header.append(f'    {WIDTHS[kind][2]} {field}'+(f'[{count[0]}]' if count else '')+';')
        action.append(']')
        header.append('};')
    return {ROOT/'lib/console/consoleviewtypes.act': '\n'.join(action+['ENDMODULE', '']),
            ROOT/'c/include/exec816/console-view-types.h': '\n'.join(header+['#endif', ''])}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Stale console view ABI: '+str(path))
        else:
            path.write_text(content)
