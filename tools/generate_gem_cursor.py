#!/usr/bin/env python3
"""Select immutable MFORM words from the hash-verified GEM4XE donor."""
import argparse
import hashlib
import json
import runpy
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
MOUSE=ROOT/'ports/gem4xe/mouse'
PIN=json.loads((MOUSE/'inputs.json').read_text())
SOURCE=MOUSE/PIN['files']['tools/gemdata.py']['local']
assert hashlib.sha256(SOURCE.read_bytes()).hexdigest()==PIN['files']['tools/gemdata.py']['sha256']
DONOR=runpy.run_path(str(SOURCE))
NAMES=['ARROW']
def output():
    text='/* Generated by tools/generate_gem_cursor.py; GEM4XE/EmuTOS artwork. */\nstatic const WORD cursorForms[][37]={\n'
    for name in NAMES:
        words=DONOR['mform_words'](name)
        text+='  { /* '+name+' */\n'+''.join('    '+','.join(f'(WORD)0x{v&65535:04x}' for v in words[i:i+8])+',\n' for i in range(0,37,8))+'  },\n'
    return text+'};\n'
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    path=ROOT/'ports/gem4xe/adapter/gem-cursor-forms.h';text=output()
    if a.check:assert path.read_text()==text,'Stale cursor masks'
    else:path.write_text(text)
