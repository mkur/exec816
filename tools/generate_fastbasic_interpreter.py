#!/usr/bin/env python3
"""Generate source interpreter records shared by assembly, Action! and C."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def products():
    a = json.loads((ROOT/'abi/fastbasic-interpreter.json').read_text())
    assert a['result']['fields']['message']+a['message_capacity']==a['result']['bytes']
    constants = dict(VERSION=a['version'], SOURCE_LIMIT=a['source_limit'],
        MESSAGE_CAPACITY=a['message_capacity'], CAP_MAGIC=int.from_bytes(a['capability']['magic'].encode(),'little'),
        CAP_BYTES=a['capability']['bytes'], CAP_OFFSET=a['capability']['entry_offset'])
    for group,prefix in [('capability','CAP'),('source','SOURCE'),('result','RESULT'),('session','SESSION'),('request','REQUEST'),('workspace','WORKSPACE')]:
        constants[prefix+'_BYTES']=a[group]['bytes']
        constants.update({prefix+'_FIELD_'+k.upper():v for k,v in a[group]['fields'].items()})
    for group,prefix in [('variants','VARIANT'),('phases','PHASE'),('commands','COMMAND'),('session_memory','SESSION')]:
        constants.update({prefix+'_'+k:v for k,v in a[group].items()})
    action='; SPDX-License-Identifier: MIT\n; Generated by tools/generate_fastbasic_interpreter.py; do not edit.\nMODULE FBINTERPABI\nUSE EXEC\n'
    assembly='; SPDX-License-Identifier: MIT\n; Generated by tools/generate_fastbasic_interpreter.py; do not edit.\n'
    header='/* SPDX-License-Identifier: MIT */\n/* Generated by tools/generate_fastbasic_interpreter.py; do not edit. */\n#ifndef EXEC816_FASTBASIC_INTERPRETER_H\n#define EXEC816_FASTBASIC_INTERPRETER_H\n#include <exec/ports.h>\n'
    for k,v in constants.items():
        action+=f'PUBLIC CONST {k}='+ (f'LONGCARD(${v:x})' if v>65535 else f'${v:x}')+'\n'
        assembly+=f'FBI_{k} = ${v:x}\n'
        header+=f'#define FBI_{k} {v}'+('UL' if v>65535 else '')+'\n'
    action+='PUBLIC TYPE Source=[\n  CARD version,bytes\n  LONGCARD source,length,job,generation,result,session\n]\n'
    action+='PUBLIC TYPE Session=[\n  EXEC.Message message\n  EXEC.MsgPort POINTER port\n]\nPUBLIC TYPE Request=[\n  EXEC.Message message\n  CARD command\n  Source source\n]\n'
    action+='PUBLIC TYPE Result=[\n  CARD version,bytes\n  LONGCARD job,generation\n  CARD phase,location\n  LONGINT primary,cause\n  CARD basic,line,column,messageBytes\n  BYTE ARRAY message(MESSAGE_CAPACITY)\n]\nENDMODULE\n'
    header+='struct ExecBasicSource {\n    UWORD version,bytes;\n    const UBYTE *source;\n    ULONG length,job,generation;\n    struct ExecBasicResult *result;\n    struct ExecBasicSession *session;\n};\n'
    header+='struct ExecBasicResult {\n    UWORD version,bytes;\n    ULONG job,generation;\n    UWORD phase,location;\n    LONG primary,cause;\n    UWORD basic,line,column,message_bytes;\n    UBYTE message[FBI_MESSAGE_CAPACITY];\n};\n'
    header+='struct ExecBasicSession {\n    struct Message message;\n    struct MsgPort EXEC_PTR *port;\n};\nstruct ExecBasicRequest {\n    struct Message message;\n    UWORD command;\n    struct ExecBasicSource source;\n};\n'
    header+='/* Borrow source/result until completion reply (session) or collection (one-shot). */\nLONG EXEC_CALL ExecBasicAttach(APTR image,const struct ExecBasicSource *source);\n#endif\n'
    return {ROOT/'lib/dos/fbinterpabi.act':action,
        ROOT/'ports/fastbasic/target/source-run.inc':assembly,
        ROOT/'c/include/exec816/fastbasic-interpreter.h':header}


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    for path,value in products().items():
        if args.check:
            if not path.exists() or path.read_text()!=value:raise SystemExit('Stale interpreter binding: '+str(path))
        else:path.write_text(value)
