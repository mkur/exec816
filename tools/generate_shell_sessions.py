#!/usr/bin/env python3
"""Generate resident shell protocol/context records and inspection offsets."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ABI = json.loads((ROOT / 'abi/shell-sessions.json').read_text())


def layout():
    sizes = {'BYTE': (1, 1), 'CARD': (2, 2), 'LONGCARD': (4, 2),
             'LONGINT': (4, 2), 'PROCESS.Result': (8, 2)}
    message = json.loads((ROOT/'abi/ports.json').read_text())['records']['Message']
    sizes['EXEC.Message'] = message['size'], message['alignment']
    records = {}
    for name, fields in {**ABI.get('protocol', {}), **ABI['records']}.items():
        offset, alignment, offsets, widths = 0, 1, {}, {}
        for field, kind in fields:
            base, count = kind[:-1].split('[') if '[' in kind else (kind, 1)
            size, align = (3, 1) if base.endswith(' POINTER') else sizes[base]
            size *= int(count)
            offset = (offset + align - 1) // align * align
            offsets[field], widths[field] = offset, size
            offset += size
            alignment = max(alignment, align)
        size = (offset + alignment - 1) // alignment * alignment
        sizes[name] = size, alignment
        records[name] = dict(size=size, alignment=alignment,
                             fields=offsets, widths=widths)
    return records


def render(records, constants=None):
    lines = ['; Generated by tools/generate_shell_sessions.py; do not edit.']
    for name, fields in records.items():
        lines += ['TYPE ' + name + '=[']
        for field, kind in fields:
            if '[' in kind:
                base, count = kind[:-1].split('[')
                lines += [f'  {base} ARRAY {field}({count})']
            else:
                lines += [f'  {kind} {field}']
        lines += [']', '']
    for name in records:
        record = layout()[name]
        lines += [f'CONST {name.upper()}_SIZE={record["size"]}']
        lines += [f'CONST {name.upper()}_{field.upper()}={offset}'
                  for field, offset in record['fields'].items()]
    lines += [f'CONST {name}={value}' for name, value in (constants or {}).items()]
    return '\n'.join(lines)+'\n'


def c_header():
    types={'BYTE':'UBYTE','CARD':'UWORD','LONGCARD':'ULONG','LONGINT':'LONG',
           'EXEC.Message':'struct Message','BYTE POINTER':'void EXEC_PTR *',
           'EXEC.MsgPort POINTER':'struct MsgPort EXEC_PTR *'}
    lines=['/* Generated by tools/generate_shell_sessions.py; do not edit. */',
           '#ifndef EXEC816_SHELL_SESSIONS_H','#define EXEC816_SHELL_SESSIONS_H',
           '#include <exec/ports.h>']
    for name,value in ABI['constants'].items():lines.append(f'#define {name} {value}')
    for name,fields in ABI['protocol'].items():
        lines.append('struct '+name+' {')
        cursor=0
        for field,kind in fields:
            base,count=kind[:-1].split('[') if '[' in kind else (kind,1)
            offset=layout()[name]['fields'][field]
            if offset>cursor:lines.append(f'    UBYTE pad{cursor}[{offset-cursor}];')
            target=types.get(base,'struct '+base)
            lines.append(f'    {target} {field}'+(f'[{count}]' if count!=1 else '')+';')
            cursor=offset+layout()[name]['widths'][field]
        if cursor<layout()[name]['size']:
            lines.append(f'    UBYTE pad{cursor}[{layout()[name]["size"]-cursor}];')
        lines.append('};')
    return '\n'.join(lines+['#endif',''])


def files():
    return {
        ROOT/'c/include/exec816/shell-sessions.h': c_header(),
        ROOT/'examples/shell/shell-context-types.inc': render(ABI['records']),
        ROOT/'examples/shell/shell-session-types.inc': render(ABI['protocol'], ABI['constants']),
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, source in files().items():
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit('Stale generated file: '+str(path))
        else:
            path.write_text(source)
