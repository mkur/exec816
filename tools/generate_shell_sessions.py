#!/usr/bin/env python3
"""Generate resident shell context records and shared inspection offsets."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ABI = json.loads((ROOT / 'abi/shell-sessions.json').read_text())


def layout():
    sizes = {'BYTE': (1, 1), 'CARD': (2, 2), 'LONGCARD': (4, 2),
             'LONGINT': (4, 2), 'PROCESS.Result': (8, 2)}
    records = {}
    for name, fields in ABI['records'].items():
        offset, alignment, offsets, widths = 0, 1, {}, {}
        for field, kind in fields:
            size, align = (3, 1) if kind.endswith(' POINTER') else sizes[kind]
            offset = (offset + align - 1) // align * align
            offsets[field], widths[field] = offset, size
            offset += size
            alignment = max(alignment, align)
        size = (offset + alignment - 1) // alignment * alignment
        sizes[name] = size, alignment
        records[name] = dict(size=size, alignment=alignment,
                             fields=offsets, widths=widths)
    return records


def files():
    lines = ['; Generated by tools/generate_shell_sessions.py; do not edit.']
    for name, fields in ABI['records'].items():
        lines += ['TYPE ' + name + '=[']
        lines += [f'  {kind} {field}' for field, kind in fields]
        lines += [']', '']
    for name, record in layout().items():
        lines += [f'CONST {name.upper()}_SIZE={record["size"]}']
        lines += [f'CONST {name.upper()}_{field.upper()}={offset}'
                  for field, offset in record['fields'].items()]
    return {ROOT/'examples/shell/shell-context-types.inc': '\n'.join(lines)+'\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, source in files().items():
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit('Stale generated file: '+str(path))
        else:
            path.write_text(source)
