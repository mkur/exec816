#!/usr/bin/env python3
"""Generate SDX constants, bindings, CRC table and service contracts."""
import argparse
import json
from pathlib import Path

from sdx_patch import manifests, selectors

ROOT = Path(__file__).resolve().parents[1]


def service_reference(abi):
    contract=abi['guest_contract']
    text='# SDX guest service subset\n\n'
    text+='<!-- Generated by tools/generate_sdx.py from abi/sdx.json. -->\n\n'
    text+='[Reference index](README.md) · [Machine-readable ABI](../../abi/sdx.json) · '
    text+='[Development evidence](../development/sdx-services.md)\n\n'
    for key in ('scope','entry','preservation','pointers','errors'):
        text+=contract[key]+'\n\n'
    text+='| Symbol | Input | Effect | Registers and flags |\n| --- | --- | --- | --- |\n'
    for name,item in abi['guest_services'].items():
        text+=f'| `{name}` | {item["inputs"]} | {item["effects"]} | {item["flags"]} |\n'
    text+='\n## Bounded operations\n\n'
    for key in ('command_limit','drive_policy','formatter','output'):
        text+=contract[key]+'\n\n'
    text+='## Error mapping\n\n| Native IoErr | Guest error |\n| --- | --- |\n'
    for native,guest in contract['native_error_map'].items():
        text+=f'| {native} | {guest} |\n'
    text+='\n| Guest error | Meaning in this subset |\n| --- | --- |\n'
    for code,meaning in contract['adapter_errors'].items():
        text+=f'| {code} | {meaning} |\n'
    text+='\nContracts were checked against the [SDX 4.50 Programming Guide]('
    text+=contract['guide']['url']+'). The frozen PDF SHA-256 is `'
    text+=contract['guide']['sha256']+'`. This subset does not implement the complete guide.\n'
    return text


def products():
    abi = json.loads((ROOT/'abi/sdx.json').read_text())
    runtime=abi['runtime']
    if (runtime['slots'],runtime['context_bytes'],runtime['context_base']) != (2,512,0x287a00):
        raise ValueError('SDX bridge context capacity or placement changed')
    if runtime['fields'] != dict(native_s=256,native_d=258,guest_s=260,event=262,bank=264):
        raise ValueError('SDX bridge context fields changed')
    if runtime['frame'] != dict(dbr=1,d=2,y=4,x=6,a=8,veneer_p=10,p=11,pc=12):
        raise ValueError('SDX guest frame changed')
    crc = abi['crc32']
    constants = '; Generated by tools/generate_sdx.py; do not edit.\n'
    constants += '.ifndef SDX_ABI_VERSION\n'
    constants += f'SDX_ABI_VERSION = {abi["version"]}\n'
    for key in ('pointer_dp', 'state_dp'):
        constants += f'SDX_CRC_{key.upper()} = ${crc[key]:02x}\n'
    for name, argument in zip(('POINTER', 'COUNT', 'STATE'), abi['imports']['Update']['arguments']):
        constants += f'SDX_CRC_ARG_{name} = {argument["offset"]+4}\n'
    table = '; Generated by tools/generate_sdx.py; CRC-32/ISO-HDLC.\n'
    table += '.export sdx_crc32_table, sdx_crc32_table_end\nsdx_crc32_table:\n'
    for index in range(crc['table_entries']):
        value = index
        for _ in range(8):
            value = (value >> 1) ^ (crc['polynomial'] if value & 1 else 0)
        table += f'    .dword ${value:08x}\n'
    table += 'sdx_crc32_table_end:\n'
    catalog = selectors(manifests(ROOT/'compat/sdx'))
    action = '; Generated by tools/generate_sdx.py; do not edit.\nMODULE SDXCATALOG\n'
    action += f'PUBLIC CONST PATCH_LIMIT={abi["patch_limit"]}\n'
    for name, value in abi['errors'].items():
        action += f'PUBLIC CONST ERROR_{name}={value}\n'
    action += '\nPUBLIC BYTE FUNC Select(LONGCARD bytes,crc)\n\n'
    seen = set()
    for (size, checksum), (_, module) in catalog.items():
        name = module['file']
        seen.add(name)
        action += f'  IF bytes={size} AND crc=${checksum:08x} THEN\n'
        action += f'    RETURN({abi["modules"][name]})\n  FI\n\n'
    if seen != set(abi['modules']):
        raise ValueError('SDX module IDs differ from manifest catalog')
    action += 'RETURN(0)\n\nENDMODULE\n'
    shared = '; Generated by tools/generate_sdx.py; do not edit.\nMODULE SDXABI\n'
    shared += 'USE O65READ\n'
    for key, value in abi['runtime'].items():
        fields = value if isinstance(value, dict) else {key:value}
        for name, number in fields.items():
            label = (key+'_' if isinstance(value, dict) else '')+name
            constants += f'SDX_{label.upper()} = ${number:x}\n'
            shared += f'PUBLIC CONST {label.upper()}=${number:x}\n'
    for name, item in abi['guest_services'].items():
        shared += f'PUBLIC CONST CALL_{name}={item["event"]}\n'
    shared += '\nPUBLIC CARD FUNC Resolve(BYTE POINTER name)\n\n'
    for name, item in abi['guest_services'].items():
        # Inline string literals use Action's length prefix: skip it explicitly.
        shared += f'  IF O65READ.Equal(name,BYTE POINTER("{name:8}")+1,8)<>0 THEN\n'
        shared += f'    RETURN(${item["address"]:x})\n  FI\n'
    shared += '\nRETURN(0)\n\nENDMODULE\n'
    return {'platform/altirraos/generated/sdx.inc': constants+'.endif\n',
            'lib/dos/sdxabi.act': shared,
            'platform/altirraos/generated/sdx-crc32-table.inc': table,
            'lib/dos/sdxcatalog.act': action,
            'docs/reference/sdx-services.md': service_reference(abi)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in products().items():
        path = ROOT/name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Stale generated file: '+str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
