#!/usr/bin/env python3
"""Generate the native SDX checksum ABI and table from abi/sdx.json."""
import argparse
import json
from pathlib import Path

from sdx_patch import manifests, selectors

ROOT = Path(__file__).resolve().parents[1]


def products():
    abi = json.loads((ROOT/'abi/sdx.json').read_text())
    crc = abi['crc32']
    constants = '; Generated by tools/generate_sdx.py; do not edit.\n'
    constants += f'SDX_ABI_VERSION = {abi["version"]}\n'
    for key in ('pointer_dp', 'state_dp'):
        constants += f'SDX_CRC_{key.upper()} = ${crc[key]:02x}\n'
    for name, argument in zip(('POINTER', 'COUNT', 'STATE'), abi['imports']['Update']['arguments']):
        constants += f'SDX_CRC_ARG_{name} = {argument["offset"]+4}\n'
    table = '; Generated by tools/generate_sdx.py; CRC-32/ISO-HDLC.\n'
    table += '.export sdx_crc32_table, sdx_crc32_table_end\nsdx_crc32_table:\n'
    for index in range(crc['table_entries']):
        value = index
        for _ in range(8):
            value = (value >> 1) ^ (crc['polynomial'] if value & 1 else 0)
        table += f'    .dword ${value:08x}\n'
    table += 'sdx_crc32_table_end:\n'
    catalog = selectors(manifests(ROOT/'compat/sdx'))
    action = '; Generated by tools/generate_sdx.py; do not edit.\nMODULE SDXCATALOG\n'
    action += f'PUBLIC CONST PATCH_LIMIT={abi["patch_limit"]}\n'
    for name, value in abi['errors'].items():
        action += f'PUBLIC CONST ERROR_{name}={value}\n'
    action += '\nPUBLIC BYTE FUNC Select(LONGCARD bytes,crc)\n\n'
    seen = set()
    for (size, checksum), (_, module) in catalog.items():
        name = module['file']
        seen.add(name)
        action += f'  IF bytes={size} AND crc=${checksum:08x} THEN\n'
        action += f'    RETURN({abi["modules"][name]})\n  FI\n\n'
    if seen != set(abi['modules']):
        raise ValueError('SDX module IDs differ from manifest catalog')
    action += 'RETURN(0)\n\nENDMODULE\n'
    return {'platform/altirraos/generated/sdx.inc': constants,
            'platform/altirraos/generated/sdx-crc32-table.inc': table,
            'lib/dos/sdxcatalog.act': action}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in products().items():
        path = ROOT/name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Stale generated file: '+str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
